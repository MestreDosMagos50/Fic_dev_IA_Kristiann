a, b = 17, 5
print(a, b)

# Operadores aritméticos
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

# Operadores relacionais
print(a == b)
print(a != b)
print(a > b)
print(a <= b)

idade = 25
print(idade)
print(18 <= idade <= 65)

# Operadores lógicos
tem_18_anos = True
tem_cnh = False
pode_dirigir = tem_18_anos and tem_cnh
print(pode_dirigir)

tem_dinheiro = True
tem_credito = False
pode_comprar = tem_dinheiro or tem_credito
print(pode_comprar)

print(not tem_cnh)

# Atribuição composta
x = 10
x += 5
x *= 2
print(x)
